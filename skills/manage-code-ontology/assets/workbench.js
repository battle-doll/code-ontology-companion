  function flattenProperties(value, prefix, rows, depth) {
    if (rows.size >= 200 || depth > 5) return;
    if (value && typeof value === "object" && !Array.isArray(value)) {
      Object.keys(value).sort().forEach(function (key) {
        if (key !== "previous") flattenProperties(value[key], prefix ? prefix + "." + key : key, rows, depth + 1);
      });
    } else rows.set(prefix, value);
  }

  function comparisonRows(item) {
    const previous = objectOrEmpty(item.previous);
    if (!Object.keys(previous).length) return null;
    const before = new Map(); const after = new Map();
    flattenProperties(previous, "", before, 0); flattenProperties(item, "", after, 0);
    return Array.from(new Set(Array.from(before.keys()).concat(Array.from(after.keys())))).sort().filter(function (key) {
      return JSON.stringify(before.get(key)) !== JSON.stringify(after.get(key));
    }).map(function (key) { return { key: key, before: before.has(key) ? before.get(key) : undefined, after: after.has(key) ? after.get(key) : undefined }; });
  }

