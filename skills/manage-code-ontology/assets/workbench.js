  function tracePaths(graph) {
    if (state.activeLens !== "impact" || !nodeById.has(state.rootId)) return [];
    const allowed = new Set(graph.edges.map(function (edge) { return edge.key; }));
    const directions = state.direction === "both" ? [true, false] : [state.direction === "incoming"];
    const result = [];
    directions.forEach(function (reversed) {
      const queue = [{ id: state.rootId, path: [], visited: new Set([state.rootId]) }];
      const limit = result.length + (directions.length === 2 ? 6 : 12);
      for (let at = 0; at < queue.length && result.length < limit; at += 1) {
        const entry = queue[at];
        if (entry.path.length >= state.depth) continue;
        const candidates = (reversed ? incoming : outgoing).get(entry.id) || [];
        for (const edge of candidates) {
          const next = reversed ? edge.source : edge.target;
          if (!allowed.has(edge.key) || entry.visited.has(next)) continue;
          const path = reversed ? [edge].concat(entry.path) : entry.path.concat([edge]);
          result.push(path);
          const visited = new Set(entry.visited); visited.add(next);
          queue.push({ id: next, path: path, visited: visited });
          if (result.length >= limit) break;
        }
      }
    });
    return result;
  }

